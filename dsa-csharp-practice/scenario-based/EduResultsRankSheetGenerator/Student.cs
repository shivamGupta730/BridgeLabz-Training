class Student
{
    private int rollNo;
    private string name;
    private int marks;

    public int RollNo
    {
        get { return rollNo; }
        set { rollNo = value; }
    }

    public string Name
    {
        get { return name; }
        set { name = value; }
    }

    public int Marks
    {
        get { return marks; }
        set { marks = value; }
    }
}
